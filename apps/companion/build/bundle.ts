/**
 * Step one of the release build: one esbuild pass over `src/main.ts` into a single CommonJS file.
 *
 * - `@customs/lcu`, `@customs/db`, `@customs/core`, `zod` and `ws` are inlined. `ws`'s optional native
 *   accelerators (`bufferutil`, `utf-8-validate`) are left external: `ws` requires them inside a try/catch
 *   and falls back to JavaScript when the require throws, which is exactly what happens inside an exe.
 * - Build-time constants (`define`): the API origin, the version, and the Riot root certificate text so the
 *   exe needs no `certs/` directory beside it (`packages/lcu/src/tls.ts` reads the file when the define is
 *   absent).
 * - `import.meta.url` (used by lcu for its file paths) is rewritten to a CommonJS equivalent so the bundle
 *   loads; the only path that matters at runtime is the certificate, and that is embedded.
 *
 * `pnpm --filter companion bundle` writes `dist/kustom.cjs`. Run it with `node` on any platform.
 */

import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { build } from 'esbuild';
import {
  apiBaseForBuild,
  BUNDLE_FILE,
  COMPANION_DIR,
  companionVersion,
  RIOT_ROOT_CA_FILE,
} from './config.js';

export interface BundleOptions {
  readonly outfile?: string;
  readonly apiBase?: string;
  readonly version?: string;
}

export interface BundleResult {
  readonly outfile: string;
  readonly apiBase: string;
  readonly version: string;
  readonly bytes: number;
}

const IMPORT_META_URL_SHIM = '__customs_night_import_meta_url';

export async function bundle(options: BundleOptions = {}): Promise<BundleResult> {
  const outfile = options.outfile ?? BUNDLE_FILE;
  const apiBase = options.apiBase ?? apiBaseForBuild();
  const version = options.version ?? companionVersion();
  const riotRootCa = readFileSync(RIOT_ROOT_CA_FILE, 'utf8');
  const uiDir = join(COMPANION_DIR, 'desktop', 'overlay');
  const uiHtml = readFileSync(join(uiDir, 'index.html'), 'utf8');
  const uiCss = readFileSync(join(uiDir, 'app.css'), 'utf8');
  const uiJs = readFileSync(join(uiDir, 'app.js'), 'utf8');

  const result = await build({
    absWorkingDir: COMPANION_DIR,
    entryPoints: ['src/main.ts'],
    outfile,
    bundle: true,
    platform: 'node',
    target: 'node24',
    format: 'cjs',
    sourcemap: false,
    minify: false,
    legalComments: 'none',
    logLevel: 'warning',
    external: ['bufferutil', 'utf-8-validate'],
    define: {
      __CUSTOMS_NIGHT_API_BASE__: JSON.stringify(apiBase),
      __CUSTOMS_NIGHT_VERSION__: JSON.stringify(version),
      __CUSTOMS_NIGHT_RIOT_ROOT_CA__: JSON.stringify(riotRootCa),
      __OVERLAY_UI_HTML__: JSON.stringify(uiHtml),
      __OVERLAY_UI_CSS__: JSON.stringify(uiCss),
      __OVERLAY_UI_JS__: JSON.stringify(uiJs),
      'import.meta.url': IMPORT_META_URL_SHIM,
    },
    banner: {
      js: [
        `// Kustom companion ${version}. Generated by apps/companion/build/bundle.ts; do not edit.`,
        `const ${IMPORT_META_URL_SHIM} = require('node:url').pathToFileURL(__filename).href;`,
      ].join('\n'),
    },
    metafile: true,
  });

  const output = Object.entries(result.metafile.outputs).find(([name]) => name.endsWith('.cjs'));
  const bytes = output ? output[1].bytes : readFileSync(outfile).byteLength;
  return { outfile, apiBase, version, bytes };
}

function isMain(): boolean {
  const entry = process.argv[1];
  return typeof entry === 'string' && /bundle\.(ts|js|cjs|mjs)$/.test(entry);
}

if (isMain()) {
  bundle().then(
    (result) => {
      console.log(
        `bundled ${result.outfile} (${(result.bytes / 1024).toFixed(0)} KiB, version ${result.version}, api ${result.apiBase})`,
      );
    },
    (error) => {
      console.error('bundle failed:', error instanceof Error ? error.message : String(error));
      process.exit(1);
    },
  );
}
