/**
 * Bundle the overlay into one CommonJS file for the Node SEA (M12).
 */

import { mkdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { build } from 'esbuild';
import {
  apiBaseForBuild,
  BUNDLE_FILE,
  DIST_DIR,
  OVERLAY_DIR,
  overlayVersion,
  RIOT_ROOT_CA_FILE,
  UI_SRC_DIR,
} from './config.js';

export interface BundleOptions {
  readonly outfile?: string;
  readonly apiBase?: string;
  readonly version?: string;
}

export interface BundleResult {
  readonly outfile: string;
  readonly apiBase: string;
  readonly version: string;
  readonly bytes: number;
}

const IMPORT_META_URL_SHIM = '__customs_night_import_meta_url';

export async function bundle(options: BundleOptions = {}): Promise<BundleResult> {
  const outfile = options.outfile ?? BUNDLE_FILE;
  const apiBase = options.apiBase ?? apiBaseForBuild();
  const version = options.version ?? overlayVersion();
  const riotRootCa = readFileSync(RIOT_ROOT_CA_FILE, 'utf8');
  const uiHtml = readFileSync(join(UI_SRC_DIR, 'index.html'), 'utf8');
  const uiCss = readFileSync(join(UI_SRC_DIR, 'app.css'), 'utf8');
  const uiJs = readFileSync(join(UI_SRC_DIR, 'app.js'), 'utf8');
  mkdirSync(DIST_DIR, { recursive: true });

  const result = await build({
    absWorkingDir: OVERLAY_DIR,
    entryPoints: ['src/main.ts'],
    outfile,
    bundle: true,
    platform: 'node',
    target: 'node24',
    format: 'cjs',
    sourcemap: false,
    minify: false,
    legalComments: 'none',
    logLevel: 'warning',
    external: ['bufferutil', 'utf-8-validate'],
    define: {
      __CUSTOMS_NIGHT_API_BASE__: JSON.stringify(apiBase),
      __CUSTOMS_NIGHT_OVERLAY_VERSION__: JSON.stringify(version),
      __CUSTOMS_NIGHT_RIOT_ROOT_CA__: JSON.stringify(riotRootCa),
      __OVERLAY_UI_HTML__: JSON.stringify(uiHtml),
      __OVERLAY_UI_CSS__: JSON.stringify(uiCss),
      __OVERLAY_UI_JS__: JSON.stringify(uiJs),
      'import.meta.url': IMPORT_META_URL_SHIM,
    },
    banner: {
      js: [
        `// Kustom Overlay ${version}. Generated by apps/overlay/build/bundle.ts; do not edit.`,
        `const ${IMPORT_META_URL_SHIM} = require('node:url').pathToFileURL(__filename).href;`,
      ].join('\n'),
    },
    metafile: true,
  });

  const output = Object.entries(result.metafile.outputs).find(([name]) => name.endsWith('.cjs'));
  const bytes = output ? output[1].bytes : readFileSync(outfile).byteLength;
  return { outfile, apiBase, version, bytes };
}

function isMain(): boolean {
  const entry = process.argv[1];
  return typeof entry === 'string' && /bundle\.(ts|js|cjs|mjs)$/.test(entry);
}

if (isMain()) {
  bundle().then(
    (result) => {
      console.log(
        `bundled ${result.outfile} (${(result.bytes / 1024).toFixed(0)} KiB, version ${result.version}, api ${result.apiBase})`,
      );
    },
    (error) => {
      console.error('bundle failed:', error instanceof Error ? error.message : String(error));
      process.exit(1);
    },
  );
}
